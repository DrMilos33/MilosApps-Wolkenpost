export function drawingPresets(type: ObjectType): DrawingPreset[] {
  return DRAWING_PRESETS[type];
}

export function drawingPreset(
  type: ObjectType,
  presetId = DRAWING_PRESETS[type][0].id,
  prefix = `preset-${Date.now()}`,
): DrawingStroke[] {
  const selected = DRAWING_PRESETS[type].find((entry) => entry.id === presetId)
    ?? DRAWING_PRESETS[type][0];
  return selected.strokes.map((entry, index) => ({
    ...entry,
    id: `${prefix}-${selected.id}-${index + 1}`,
    points: entry.points.map((point) => ({ ...point })),
  }));
}
