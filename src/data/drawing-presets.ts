import type { DrawingStroke, ObjectType } from '../types';

export interface DrawingPreset {
  id: string;
  strokes: DrawingStroke[];
}

function stroke(id: string, points: Array<[number, number]>): DrawingStroke {
  return {
    id,
    points: points.map(([x, y]) => ({ x, y, pressure: 0.55 })),
  };
}

function preset(id: string, strokes: DrawingStroke[]): DrawingPreset {
  return { id, strokes };
}

